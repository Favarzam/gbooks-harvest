"""Generate public/js/html-entities.js from Python's own html module tables.

The web app uses these tables to decode text snippets exactly like
html.unescape() does in core.py. Re-run after upgrading Python:

    python3 scripts/build_html_entities.py
"""

import html
import json
from html.entities import html5
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "public" / "js" / "html-entities.js"


def dump(value) -> str:
    return json.dumps(value, ensure_ascii=True, separators=(",", ":"))


charrefs = [[code, char] for code, char in sorted(html._invalid_charrefs.items())]
codepoints = sorted(html._invalid_codepoints)

OUT.write_text(
    "// Generated by scripts/build_html_entities.py from Python's html module. Do not edit.\n"
    f"export const HTML5 = new Map(Object.entries({dump(html5)}));\n"
    f"export const INVALID_CHARREFS = new Map({dump(charrefs)});\n"
    f"export const INVALID_CODEPOINTS = new Set({dump(codepoints)});\n",
    encoding="utf-8",
)
print(f"Wrote {OUT.relative_to(OUT.parents[2])} ({len(html5)} named references)")
